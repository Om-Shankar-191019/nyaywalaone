#!/usr/bin/env node
/**
 * Day 26: `docs/api.md` is generated, not hand-maintained.
 *
 *   node scripts/api-doc.js            # print
 *   node scripts/api-doc.js > ../docs/api.md
 *
 * The list comes from the Express router itself, so a route added in code and
 * forgotten in the doc is impossible; the only hand-written part is the table
 * of error codes.
 */
import 'dotenv/config';

const { createApp } = await import('../app.js');

const app = createApp();

/**
 * Recover a mounted router's prefix from its layer regexp, without a regexp
 * literal: the source `/^\/api\/auth\/?(?=\/|$)/i` becomes `/api/auth`.
 */
function mountPathOf(layer) {
  const source = layer.regexp?.source ?? '';
  if (!source.startsWith('^')) return null;
  const rest = source.slice(1).split('\\/?(?=')[0];
  const path = rest.endsWith('$') ? rest.slice(0, -1) : rest;
  const slashed = path.split('\\/').join('/');
  if (!slashed.startsWith('/')) return null;
  return slashed.replace(/\/$/, '');
}

/** Express stores routes in a nested stack; flatten it in declaration order. */
function collect(stack, prefix = '') {
  const routes = [];
  for (const layer of stack ?? []) {
    if (layer.route) {
      const path = prefix + layer.route.path;
      for (const [method, enabled] of Object.entries(layer.route.methods)) {
        if (enabled) routes.push({ method: method.toUpperCase(), path });
      }
      continue;
    }
    if (!layer.handle?.stack) continue;
    const mount = mountPathOf(layer);
    if (mount === null) continue;
    routes.push(...collect(layer.handle.stack, prefix + mount));
  }
  return routes;
}

const routes = collect(app._router?.stack ?? [])
  .map((route) => ({ ...route, path: route.path.replace(/\/+/g, '/') }))
  .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const seen = new Set();
const unique = routes.filter((route) => {
  const key = `${route.method} ${route.path}`;
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

const lines = [
  '# API reference',
  '',
  '<!-- Generated by `node scripts/api-doc.js` — do not edit by hand. -->',
  '',
  `The routes below are read from the Express router at ${new Date().toISOString().slice(0, 10)}.`,
  'Every response is one envelope: `{ "data": ... }` on success and',
  '`{ "error": { "code", "message", "details?" } }` on failure.',
  '',
  '| Method | Path |',
  '|---|---|',
  ...unique.map((route) => `| \`${route.method}\` | \`${route.path}\` |`),
  '',
  '## Error codes',
  '',
  '| Code | Status | Meaning |',
  '|---|---|---|',
  '| `VALIDATION_ERROR` | 400 | A Zod schema rejected the body or query. |',
  '| `INVALID_JSON` | 400 | The body did not parse. |',
  '| `UNAUTHENTICATED` | 401 | No valid access token, or the refresh token was replayed. |',
  '| `FORBIDDEN` | 403 | The role or membership check refused the call. |',
  '| `NOT_FOUND` | 404 | Missing row, or a row the caller may not see (a 404, not a 403). |',
  '| `DAILY_SUBMISSION_LIMIT` | 409 | The per-student daily submission ceiling was reached. |',
  '| `LATE_NOT_ALLOWED` | 409 | The assignment closed and does not accept late work. |',
  '| `ASSIGNMENT_NOT_PUBLISHED` | 409 | No active rule set, so there is nothing to grade against. |',
  '| `PROVIDER_BUDGET_EXCEEDED` | 429 | The daily sandbox budget is spent. Resets at 00:00 UTC. |',
  '| `PROVIDER_RATE_LIMITED` | 429 | The sandbox answered 429; the retry helper already backed off. |',
  '| `PROVIDER_AUTH` | 502 | The sandbox rejected the key. Check `ONLINECOMPILER_API_KEY`. |',
  '| `PROVIDER_UNAVAILABLE` | 502/503 | The sandbox could not be reached or is queuing. |',
  '| `DB_SCHEMA_OUT_OF_DATE` | 503 | Migrations were not applied. Run `npm run db:deploy`. |',
  '| `DB_UNAVAILABLE` | 503 | The database is unreachable. |',
  '| `INTERNAL_ERROR` | 500 | A bug. The body carries `details.requestId` and the log has the same id. |',
  '',
  '## Readiness',
  '',
  '`GET /api/health/ready` answers "why can a submission fail here?" in one call:',
  'database reachable, schema current, provider key accepted, budget remaining.',
  'It returns `200` when every check passes and `503` with the failing checks otherwise.',
  '',
];

process.stdout.write(`${lines.join('\n')}\n`);
process.exit(0);
